class CatLogo(QWidget):
    """Animated cat-with-headphones logo.

    The cat bobs to the beat, its eyes follow the mouse pointer, it blinks, falls asleep after 10 s
    without mouse movement and wakes up (with a blink) when the pointer moves; clicking it makes it happy.
    """
    IDLE_SLEEP = 10.0

    def __init__(self, engine=None, size=56, parent=None):
        super().__init__(parent)
        self.engine = engine
        self.setFixedSize(size, size)
        self.setCursor(Qt.CursorShape.PointingHandCursor)
        self._renderer = QSvgRenderer(self)
        self._t0 = time.monotonic()
        self._last = self._t0
        self._look = [0.0, 0.0]
        self._target = [0.0, 0.0]
        self._sleep = 0.0
        self._sleeping = False
        self._blink = None
        self._tap = None
        self._last_cursor = None
        self._last_move = 0.0
        self._idle_at = self._t0 + self.IDLE_SLEEP
        self._next_blink = self._t0 + 2.2 + random.random() * 3.0
        self._second_blink = None
        self._timer = QTimer(self)
        self._timer.timeout.connect(self._tick)
        self._frame()

    # -- clocks ------------------------------------------------------------------------------------------
    def showEvent(self, e):
        self._last = time.monotonic()
        self._timer.start(33)
        super().showEvent(e)

    def hideEvent(self, e):
        self._timer.stop()
        super().hideEvent(e)

    def _reduced(self):
        return bool(getattr(self.engine, "reduced", False))

    def _wake(self, now):
        self._sleeping = False
        self._start_blink()
        self._second_blink = now + 0.3

    def _start_blink(self):
        self._blink = 0.0

    def _on_move(self, pos, now):
        r = self.rect()
        local = self.mapFromGlobal(pos)
        dx = local.x() - r.width() / 2.0
        dy = local.y() - r.height() * 0.57
        d = math.hypot(dx, dy) or 1.0
        k = min(d / (r.width() * 0.5), 1.0)
        self._target = [dx / d * k, dy / d * k]
        if self._sleeping:
            self._wake(now)
        elif now - self._last_move > 0.8:
            self._start_blink()
        self._last_move = now
        self._idle_at = now + self.IDLE_SLEEP

    def _tick(self):
        now = time.monotonic()
        dt = min(0.1, now - self._last)
        self._last = now
        # pointer (only while NILKON is the active window)
        try:
            if QApplication.activeWindow() is not None:
                pos = QCursor.pos()
                if pos != self._last_cursor:
                    self._last_cursor = pos
                    self._on_move(pos, now)
        except Exception:
            pass
        if not self._sleeping and now >= self._idle_at:
            self._sleeping = True
            self._target = [0.0, 0.0]
        f = 1.0 - (1.0 - 0.14) ** (dt * 60.0)
        goal = (0.0, 0.0) if self._sleeping else self._target
        self._look[0] += (goal[0] - self._look[0]) * f
        self._look[1] += (goal[1] - self._look[1]) * f
        g = 1.0 - (1.0 - 0.06) ** (dt * 60.0)
        self._sleep += ((1.0 if self._sleeping else 0.0) - self._sleep) * g
        if self._blink is not None:
            self._blink += dt / 0.22
            if self._blink >= 1.0:
                self._blink = None
        if self._second_blink is not None and now >= self._second_blink:
            self._second_blink = None
            self._start_blink()
        if now >= self._next_blink:
            if not self._sleeping:
                self._start_blink()
                if random.random() < 0.25:
                    self._second_blink = now + 0.3
            self._next_blink = now + 2.2 + random.random() * 3.0
        if self._tap is not None:
            self._tap += dt
            if self._tap >= 1.1:
                self._tap = None
        self._frame()
        self.update()

    def _frame(self):
        svg = art.logo_svg(self._last - self._t0, tuple(self._look), self._sleep, self._blink, self._tap,
                           self._reduced())
        self._renderer.load(QByteArray(svg.encode("utf-8")))

    def mousePressEvent(self, e):
        if e.button() == Qt.MouseButton.LeftButton:
            now = time.monotonic()
            if self._sleeping:
                self._wake(now)
            self._tap = 0.0
            self._idle_at = now + self.IDLE_SLEEP
            e.accept()
            return
        super().mousePressEvent(e)

    def paintEvent(self, _e):
        p = QPainter(self)
        p.setRenderHint(QPainter.RenderHint.Antialiasing)
        p.setRenderHint(QPainter.RenderHint.SmoothPixmapTransform)
        self._renderer.render(p, QRectF(self.rect()))


