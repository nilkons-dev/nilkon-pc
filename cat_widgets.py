"""Qt widgets for the cat artwork: the animated logo and the cat-ear player buttons.

The artwork itself is generated by cat_art.py (SVG strings); these classes only run the animation
clocks, handle the mouse and render with QSvgRenderer.
"""
import math
import random
import time

from PySide6.QtCore import Qt, QRectF, QByteArray, QTimer, QSize
from PySide6.QtGui import QCursor, QPainter
from PySide6.QtSvg import QSvgRenderer
from PySide6.QtWidgets import QWidget, QAbstractButton, QApplication

import cat_art as art
from theme import T


class Tween:
    """CSS-transition style value: eases from its current value to a new target."""

    def __init__(self, value, duration, curve):
        self.value = float(value)
        self.target = float(value)
        self._from = float(value)
        self._t = 1.0
        self.duration = duration
        self.curve = curve

    def set(self, target):
        target = float(target)
        if target != self.target:
            self.target = target
            self._from = self.value
            self._t = 0.0

    def step(self, dt):
        if self._t >= 1.0:
            return False
        self._t = min(1.0, self._t + dt / self.duration)
        self.value = self._from + (self.target - self._from) * self.curve(self._t)
        if self._t >= 1.0:
            self.value = self.target
        return True

    @property
    def moving(self):
        return self._t < 1.0


