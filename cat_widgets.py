class CatButton(QAbstractButton):
    """Player button with cat ears. kind: toggle (shuffle / repeat), prev, next, play.

    Same small API as GButton: set_icon(name), set_active(bool); plus set_badge(text).
    """

    def __init__(self, kind, icon=None, scale=1.0, parent=None):
        super().__init__(parent)
        self._kind = kind
        self._icon = icon or ("play" if kind == "play" else kind if kind != "toggle" else "shuffle")
        self._badge = ""
        self._active = False
        self._scale = scale
        w, h = art.PLAY if kind == "play" else art.SMALL
        self.setFixedSize(int(w * scale), int(h * scale))
        self.setCursor(Qt.CursorShape.PointingHandCursor)
        self.setFocusPolicy(Qt.FocusPolicy.NoFocus)
        self._renderer = QSvgRenderer(self)
        self._hover = Tween(0.0, 0.15, art.smooth)
        self._press = Tween(1.0, 0.18, lambda u: art.bezier(.3, 1.6, .5, 1, u))
        self._paw = Tween(0.0, 0.30, lambda u: art.bezier(.3, 1.9, .5, 1, u))
        self._tap = None
        self._pop = None
        self._last = time.monotonic()
        self._timer = QTimer(self)
        self._timer.timeout.connect(self._tick)
        self.pressed.connect(lambda: self._press.set(0.88))
        self.released.connect(lambda: self._press.set(1.0))
        self.clicked.connect(self._on_click)
        self._wake()

    # -- public API ----------------------------------------------------------------------------------------
    def set_icon(self, name):
        badge = ""
        if name == "repeat-1":
            name, badge = "repeat", "1"
        if name != self._icon or badge != self._badge:
            changed = name != self._icon
            self._icon, self._badge = name, badge
            if self._kind == "play" and changed:
                self._pop = 0.0
            self._wake()
            self.update()

    def set_active(self, on):
        on = bool(on)
        if on != self._active:
            self._active = on
            self._paw.set(1.0 if on else 0.0)
            self._wake()
            self.update()

    def set_badge(self, text):
        self._badge = text or ""
        self.update()

    def sizeHint(self):
        return QSize(self.width(), self.height())

    # -- animation ----------------------------------------------------------------------------------------
    def _glowing(self):
        return self._kind == "play" and self._icon == "pause" and not getattr(self.window(), "isMinimized", lambda: False)()

    def _wake(self):
        if not self._timer.isActive():
            self._last = time.monotonic()
            self._timer.start(16)

    def enterEvent(self, e):
        self._hover.set(1.0)
        self._wake()
        super().enterEvent(e)

    def leaveEvent(self, e):
        self._hover.set(0.0)
        self._press.set(1.0)
        self._wake()
        super().leaveEvent(e)

    def _on_click(self):
        self._tap = 0.0
        self._wake()

    def _tick(self):
        now = time.monotonic()
        dt = min(0.1, now - self._last)
        self._last = now
        busy = False
        for tw in (self._hover, self._press, self._paw):
            busy = tw.step(dt) or tw.moving or busy
        if self._tap is not None:
            self._tap += dt
            if self._tap >= (0.55 if self._kind != "toggle" else 0.6):
                self._tap = None
            else:
                busy = True
        if self._pop is not None:
            self._pop += dt / 0.3
            if self._pop >= 1.0:
                self._pop = None
            else:
                busy = True
        glow = self._glowing()
        if not busy and not glow:
            self._timer.stop()
        self.update()

    def _render(self):
        glow = None
        if self._glowing():
            glow = (time.monotonic() % 2.4) / 2.4
        svg = art.button_svg(self._kind, T.dark, T.c1, icon=self._icon, hover=self._hover.value, on=self._active,
                             paw=self._paw.value, press=self._press.value, tap=self._tap, pop=self._pop,
                             glow=glow, badge=self._badge)
        self._renderer.load(QByteArray(svg.encode("utf-8")))

    def showEvent(self, e):
        if self._glowing():
            self._wake()
        super().showEvent(e)

    def paintEvent(self, _e):
        self._render()
        p = QPainter(self)
        p.setRenderHint(QPainter.RenderHint.Antialiasing)
        p.setRenderHint(QPainter.RenderHint.SmoothPixmapTransform)
        if not self.isEnabled():
            p.setOpacity(0.4)
        self._renderer.render(p, QRectF(self.rect()))
